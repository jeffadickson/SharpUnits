bool Equal(JsonNode? a,JsonNode? b)
{
    if(a is JsonObject ao&&b is JsonObject bo)return ao.Count==bo.Count&&ao.All(p=>bo.ContainsKey(p.Key)&&Equal(p.Value,bo[p.Key]));
    if(a is JsonArray aa&&b is JsonArray ba)return aa.Count==ba.Count&&aa.Zip(ba).All(p=>Equal(p.First,p.Second));
    if(a is JsonValue av&&b is JsonValue bv&&av.TryGetValue<double>(out var x)&&bv.TryGetValue<double>(out var y))
        return x==y||double.IsFinite(x)&&double.IsFinite(y)&&Math.Abs(x-y)<=Math.Max(Math.Abs(x),Math.Abs(y))*1e-13;
    return JsonNode.DeepEquals(a,b);
}
